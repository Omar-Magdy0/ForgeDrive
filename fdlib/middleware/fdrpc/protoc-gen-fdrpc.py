import sys
from google.protobuf.compiler import plugin_pb2
import fdrpc_pb2
from functools import reduce


def c_type_name(proto_type):
    return proto_type.rsplit(".", 1)[-1]

def generate_service_enum(service):
    lines = [f"enum Id : uint16_t {{"]
    for method in service.method: lines.append(f"    Id_{method.name} = {method.options.Extensions[fdrpc_pb2.id]},")
    lines.append("};")
    return "\n".join(lines)


def generate_service_registry(service, methods):
    def max_expression(items):
        return reduce(lambda a, b: f"FDRPC_MAX({a}, {b})", items, "0")
    request_sizes = [f"{m['input']}_size" for m in methods]
    response_sizes = [f"{m['output']}_size" for m in methods]
    request_struct_sizes = [f"sizeof({m['input']})" for m in methods]
    response_struct_sizes = [f"sizeof({m['output']})" for m in methods]
    lines = [
        f"namespace {c_type_name(service.name)}",
        "{",
        "#define FDRPC_MAX(a, b) ( ((a) > (b)) ? (a) : (b))\n"
        "using namespace Rpc;",
        "constexpr uint16_t MAX_REQUEST_ENCODED_SIZE = " + max_expression(request_sizes) + ";",
        "constexpr uint16_t MAX_RESPONSE_ENCODED_SIZE = " + max_expression(response_sizes) + ";",
        "constexpr uint16_t MAX_REQUEST_STRUCT_SIZE = " + max_expression(request_struct_sizes) + ";",
        "constexpr uint16_t MAX_RESPONSE_STRUCT_SIZE = " + max_expression(response_struct_sizes) + ";",
        generate_service_enum(service),
        "template<Id id>\nstruct MethodTraits;"
        ""
    ]
    for method in methods: lines.append(f"Rpc::DispatchStatus {method['name']}(DispatchStack);")
    lines.append("inline constexpr Method registry[] = {")
    for method in sorted(methods, key=lambda m: m["id"]):
        lines.append(f"  {{ Id_{method['name']}, &{method['input']}_msg, &{method['output']}_msg, {method['name']} }},")
    lines.append("};")
    for method in methods:
        lines.append(
            f"template<> struct MethodTraits<Fdmc::Id::Id_{method['name']}> {{\n"
            f"    using Arg = {method['input']};\n"
            f"    using Ret = {method['output']};\n"
            f"}};"
        )
    lines.append("#undef FDRPC_MAX \n}")
    return "\n".join(lines)

def nanopb_rpc(filename, proto):
    content = [
        "// Generated by fdrpc plugin",
        "#pragma once",
        f'extern "C" {{\n#include "{filename.removesuffix(".proto")}.pb.h"\n}}\n'
        "#include \"Rpc.h\"",
    ]
    for service in proto.service:
        methods = []
        for method in service.method:
            methods.append({
                "name": c_type_name(method.name),
                "input": c_type_name(method.input_type),
                "output": c_type_name(method.output_type),
                "id": method.options.Extensions[fdrpc_pb2.id]
            })
        #lets make a macro for largest serialized size on input and output, based on nanopb sizes
        content.extend([
            "",
            generate_service_registry(service, methods),
            "",
        ])
    return content

def fdrpc_header():
    return """\
#pragma once
"""

def generate(request):
    response = plugin_pb2.CodeGeneratorResponse()
    output = response.file.add()
    output.name = "fdrpc.pb.h"
    output.content = fdrpc_header()
    for filename in request.file_to_generate:
        # Find the corresponding FileDescriptorProto
        proto = next(f for f in request.proto_file if f.name == filename)
        output = response.file.add()
        output.name = filename.removesuffix(".proto") + ".rpc.h"
        output.content = "\n".join(nanopb_rpc(filename, proto))
    return response


def main():
    request = plugin_pb2.CodeGeneratorRequest.FromString(
        sys.stdin.buffer.read()
    )
    response = generate(request)
    sys.stdout.buffer.write(response.SerializeToString())


if __name__ == "__main__":
    main()
